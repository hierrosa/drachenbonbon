// Streuung aus kleinen Punkten — für Pulver und Splitter statt einer
// glatten Flüssigkeitsfläche.
function koernung(punkte, farbe = 'rgba(255,255,255,.5)') {
  return punkte.map(([x, y, r]) =>
    `<circle cx="${x}" cy="${y}" r="${r}" fill="${farbe}"/>`).join('');
}

