// --- Vollgrafik-Zutaten (aus Inkscape). Nur die sichtbare Ebene, umgefärbt auf
//     die Zutatenfarbe (leuchtend), mit etwas Textur. Breite bleibt 52,
//     Höhe proportional zur viewBox (siehe .glas.grafik im CSS). ---
const heller = (hex, f = 1.5) => {
  const n = parseInt(hex.slice(1), 16);
  const r = Math.min(255, Math.round((n >> 16) * f));
  const g = Math.min(255, Math.round((n >> 8 & 255) * f));
  const b = Math.min(255, Math.round((n & 255) * f));
  return `rgb(${r},${g},${b})`;
};

// Knallige (aufgesättigte) Variante — Kanäle vom Mittelwert wegspreizen.
const knallig = (hex, sat = 1.8) => {
  const n = parseInt(hex.slice(1), 16);
  const r = n >> 16, g = n >> 8 & 255, b = n & 255;
  const avg = (r + g + b) / 3;
  const cl = (v) => Math.max(0, Math.min(255, Math.round(avg + (v - avg) * sat)));
  return `rgb(${cl(r)},${cl(g)},${cl(b)})`;
};

// Richtung Weiß mischen (für den hellen, weißlichen unteren Bereich).
const mixWeiss = (hex, t = 0.7) => {
  const n = parseInt(hex.slice(1), 16);
  const m = (v) => Math.round(v + (255 - v) * t);
  return `rgb(${m(n >> 16)},${m(n >> 8 & 255)},${m(n & 255)})`;
};

// Deterministische Speckle-Streuung (stabil beim Neurendern).
function speckle(b, n, seed) {
  let s = seed;
  const rnd = () => (s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  let out = '';
  for (let i = 0; i < n; i++) {
    const x = (b.x + rnd() * b.w).toFixed(0);
    const y = (b.y + rnd() * b.h).toFixed(0);
    const r = (1.5 + rnd() * 2.3).toFixed(1);
    const dark = rnd() < 0.32;
    out += `<circle cx="${x}" cy="${y}" r="${r}" fill="${dark ? '#000' : '#fff'}" opacity="${dark ? '.35' : '.3'}"/>`;
  }
  return out;
}

// Vollgrafik-Glas: Körper in Zutatenfarbe + Schattierung/Glanz/Speckles (auf
// den Körper geclippt) und die Akzent-Formen (abwechselnd hell/dunkel).
function grafikGlas(id, tx, ty, hell, dunkel, bodyD, accents, b) {
  const akz = accents.map((d, i) =>
    `<path d="${d}" fill="${i % 2 ? dunkel : heller(hell, 1.35)}" stroke="${dunkel}" stroke-width="1.6" stroke-linejoin="round"/>`).join('');
  return `<defs>
      <clipPath id="cb-${id}"><path d="${bodyD}"/></clipPath>
      <linearGradient id="sh-${id}" x1="0" y1="0" x2="0.3" y2="1">
        <stop offset="0%"  stop-color="#fff" stop-opacity=".5"/>
        <stop offset="38%" stop-color="#fff" stop-opacity="0"/>
        <stop offset="68%" stop-color="#000" stop-opacity="0"/>
        <stop offset="100%" stop-color="#000" stop-opacity=".5"/>
      </linearGradient>
    </defs>
    <g transform="translate(${tx} ${ty})">
      <path d="${bodyD}" fill="url(#f-${id})" stroke="${dunkel}" stroke-width="2.4" stroke-linejoin="round"/>
      <g clip-path="url(#cb-${id})">
        <rect x="${b.x - 15}" y="${b.y - 15}" width="${b.w + 45}" height="${b.h + 45}" fill="url(#sh-${id})"/>
        <path d="M${(b.x + b.w * 0.12).toFixed(0)} ${(b.y + 4).toFixed(0)} q-6 ${(b.h * 0.5).toFixed(0)} 2 ${b.h.toFixed(0)}" fill="none" stroke="#fff" stroke-width="6" stroke-linecap="round" opacity=".26"/>
        ${speckle(b, 11, id.length * 97 + 13)}
      </g>
      ${akz}
    </g>`;
}

